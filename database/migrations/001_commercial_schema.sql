BEGIN;

CREATE SCHEMA nazareth;

CREATE TABLE nazareth.profiles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id uuid UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
  name text NOT NULL,
  role text NOT NULL CHECK (role IN ('admin', 'client')),
  is_active boolean NOT NULL DEFAULT true,
  is_protected boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (NOT is_protected OR (role = 'admin' AND is_active AND auth_user_id IS NOT NULL))
);

CREATE TABLE nazareth.categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE
);

CREATE TABLE nazareth.products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer NOT NULL REFERENCES nazareth.categories(id),
  name text NOT NULL,
  unit text NOT NULL,
  cost_price numeric(10,2) NOT NULL CHECK (cost_price >= 0),
  sale_price numeric(10,2) NOT NULL CHECK (sale_price >= 0),
  current_stock numeric(10,2) NOT NULL DEFAULT 0 CHECK (current_stock >= 0),
  min_stock_threshold numeric(10,2) NOT NULL DEFAULT 5 CHECK (min_stock_threshold >= 0),
  image_url text,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE nazareth.customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer UNIQUE REFERENCES nazareth.profiles(id),
  name text NOT NULL,
  phone text,
  points integer NOT NULL DEFAULT 0,
  total_spent numeric(12,2) NOT NULL DEFAULT 0,
  visit_count integer NOT NULL DEFAULT 0,
  last_purchase_date timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE nazareth.sales (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receipt_number text,
  user_id integer NOT NULL REFERENCES nazareth.profiles(id),
  customer_id integer REFERENCES nazareth.customers(id),
  total_amount numeric(12,2) NOT NULL CHECK (total_amount >= 0),
  payment_method text NOT NULL CHECK (payment_method IN ('efectivo', 'yape', 'plin')),
  payment_reference text CHECK (payment_reference IS NULL OR payment_reference ~ '[^[:space:]]'),
  status text NOT NULL DEFAULT 'completed',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE nazareth.sale_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id integer NOT NULL REFERENCES nazareth.sales(id),
  product_id integer NOT NULL REFERENCES nazareth.products(id),
  quantity numeric(10,2) NOT NULL CHECK (quantity > 0),
  unit_price numeric(10,2) NOT NULL CHECK (unit_price >= 0),
  subtotal numeric(12,2) NOT NULL CHECK (subtotal >= 0)
);

CREATE TABLE nazareth.promotions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES nazareth.products(id),
  title text,
  discount_type text NOT NULL CHECK (discount_type IN ('percentage', 'fixed')),
  discount_value numeric(10,2) NOT NULL CHECK (discount_value > 0),
  start_date timestamptz NOT NULL,
  end_date timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'scheduled' CHECK (status IN ('active', 'scheduled', 'paused', 'finished')),
  usage_count integer NOT NULL DEFAULT 0,
  revenue numeric(12,2) NOT NULL DEFAULT 0,
  created_by integer REFERENCES nazareth.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (end_date >= start_date),
  CHECK (discount_type <> 'percentage' OR discount_value <= 100)
);

CREATE TABLE nazareth.customer_saved_promotions (
  customer_id integer NOT NULL REFERENCES nazareth.customers(id),
  promotion_id integer NOT NULL REFERENCES nazareth.promotions(id) ON DELETE CASCADE,
  saved_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (customer_id, promotion_id)
);

CREATE TABLE nazareth.customer_favorites (
  customer_id integer NOT NULL REFERENCES nazareth.customers(id),
  product_id integer NOT NULL REFERENCES nazareth.products(id),
  PRIMARY KEY (customer_id, product_id)
);

CREATE TABLE nazareth.product_lists (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES nazareth.customers(id),
  name text
);

CREATE TABLE nazareth.product_list_items (
  list_id integer NOT NULL REFERENCES nazareth.product_lists(id) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES nazareth.products(id),
  PRIMARY KEY (list_id, product_id)
);

CREATE TABLE nazareth.reservations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES nazareth.customers(id),
  pickup_code text NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'pending',
  estimated_total numeric(12,2) NOT NULL CHECK (estimated_total >= 0),
  pickup_deadline timestamptz NOT NULL DEFAULT (now() + interval '24 hours'),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (pickup_deadline = created_at + interval '24 hours')
);

CREATE TABLE nazareth.reservation_items (
  reservation_id integer NOT NULL REFERENCES nazareth.reservations(id),
  product_id integer NOT NULL REFERENCES nazareth.products(id),
  line_position smallint NOT NULL CHECK (line_position BETWEEN 1 AND 3),
  quantity numeric(10,2) NOT NULL DEFAULT 1 CHECK (quantity > 0),
  unit_price numeric(10,2) NOT NULL CHECK (unit_price >= 0),
  PRIMARY KEY (reservation_id, product_id),
  UNIQUE (reservation_id, line_position)
);

CREATE TABLE nazareth.purchase_orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_name text NOT NULL CHECK (supplier_name ~ '[^[:space:]]'),
  supplier_ruc text NOT NULL CHECK (supplier_ruc ~ '[^[:space:]]'),
  supplier_phone text NOT NULL CHECK (supplier_phone ~ '[^[:space:]]'),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'received', 'cancelled')),
  estimated_total numeric(12,2) NOT NULL CHECK (estimated_total >= 0),
  created_by integer NOT NULL REFERENCES nazareth.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE nazareth.purchase_order_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES nazareth.purchase_orders(id),
  product_id integer NOT NULL REFERENCES nazareth.products(id),
  quantity numeric(10,2) NOT NULL CHECK (quantity > 0),
  unit_cost numeric(10,2) NOT NULL CHECK (unit_cost > 0),
  received_quantity numeric(10,2) NOT NULL DEFAULT 0 CHECK (received_quantity BETWEEN 0 AND quantity),
  UNIQUE (order_id, id)
);

CREATE TABLE nazareth.receipts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES nazareth.purchase_orders(id),
  reference text NOT NULL UNIQUE CHECK (reference ~ '[^[:space:]]'),
  received_by integer NOT NULL REFERENCES nazareth.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (order_id, id)
);

CREATE TABLE nazareth.receipt_items (
  order_id integer NOT NULL,
  receipt_id integer NOT NULL,
  order_item_id integer NOT NULL,
  quantity numeric(10,2) NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (receipt_id, order_item_id),
  FOREIGN KEY (order_id, receipt_id) REFERENCES nazareth.receipts(order_id, id),
  FOREIGN KEY (order_id, order_item_id) REFERENCES nazareth.purchase_order_items(order_id, id)
);

CREATE TABLE nazareth.inventory_movements (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id integer NOT NULL REFERENCES nazareth.products(id),
  type text NOT NULL CHECK (type IN ('entry', 'sale', 'adjustment')),
  quantity_change numeric(10,2) NOT NULL CHECK (quantity_change <> 0),
  stock_before numeric(10,2),
  stock_after numeric(10,2),
  reason text,
  sale_id integer REFERENCES nazareth.sales(id),
  receipt_id integer REFERENCES nazareth.receipts(id),
  created_by integer REFERENCES nazareth.profiles(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (type <> 'adjustment' OR (reason IS NOT NULL AND reason ~ '[^[:space:]]')),
  CHECK ((stock_before IS NULL AND stock_after IS NULL) OR
    (stock_before IS NOT NULL AND stock_after IS NOT NULL AND stock_before >= 0 AND stock_after >= 0
      AND stock_after = stock_before + quantity_change))
);

CREATE INDEX sales_created_at_idx ON nazareth.sales (created_at);
CREATE INDEX sales_customer_created_at_idx ON nazareth.sales (customer_id, created_at);
CREATE INDEX sale_items_sale_id_idx ON nazareth.sale_items (sale_id);
CREATE INDEX inventory_movements_product_created_at_idx ON nazareth.inventory_movements (product_id, created_at);

COMMIT;
